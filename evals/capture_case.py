"""Capture an eval case from GitHub Actions: raw job logs + meta.yaml.

    uv run python -m evals.capture_case --repo owner/name --case case-04 \\
        --run <maven_run_id> --run <gradle_run_id> [--force]

Read-only (``gh api`` GETs only). For each run it records ids, event, conclusion and
attempts from the API, saves the failed job's log exactly as GitHub returns it, and
derives ``base_sha`` (PR merge base) and ``jdk`` from the log. Other runs of the same
head SHA are recorded as ``related_runs``. Branch names and PR titles are never
written (the loader's leak check runs on the generated meta before saving).

``expected.yaml`` (the answer key) is never touched; write it by hand.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol, cast, get_args

import yaml

from agent.schema import BuildTool
from evals.consistency import check_case
from evals.loader import CASES_DIR, CaseError, CaseMeta, find_forbidden_keys
from evals.log_facts import extract_log_facts

TOOLS: tuple[str, ...] = get_args(BuildTool)
LOG_NAMES = {tool: f"{tool}.log" for tool in TOOLS}
HEADER = (
    "# Generated by evals/capture_case.py from the GitHub API and the job logs.\n"
    "# Do not edit by hand; re-run the capture instead. No branch names / PR titles.\n"
)


class CaptureError(RuntimeError):
    pass


class GitHub(Protocol):
    def get_json(self, path: str) -> Any: ...
    def get_bytes(self, path: str) -> bytes: ...


class GhCli:
    """GitHub API through the authenticated ``gh`` CLI (GET requests only)."""

    def _run(self, args: list[str]) -> bytes:
        if shutil.which("gh") is None:
            raise CaptureError("gh CLI not found; install it and run `gh auth login`")
        proc = subprocess.run(["gh", "api", "--method", "GET", *args], capture_output=True)
        if proc.returncode != 0:
            err = proc.stderr.decode(errors="replace").strip()
            raise CaptureError(f"gh api {args[-1]} failed: {err}")
        return proc.stdout

    def get_json(self, path: str) -> Any:
        return json.loads(self._run([path]))

    def get_bytes(self, path: str) -> bytes:
        return self._run(["--allow-escape-sequences", path])


@dataclass(frozen=True)
class RunSpec:
    run_id: int
    tool: str | None = None  # inferred from the workflow when None


def parse_run_spec(text: str) -> RunSpec:
    tool, sep, ident = text.rpartition("=")
    if sep and tool not in TOOLS:
        raise argparse.ArgumentTypeError(f"unknown build tool {tool!r} (use {TOOLS})")
    if not ident.isdigit():
        raise argparse.ArgumentTypeError(f"run id must be numeric, got {ident!r}")
    return RunSpec(run_id=int(ident), tool=tool or None)


def infer_tool(run: dict[str, Any]) -> str | None:
    haystack = f"{run.get('path', '')} {run.get('name', '')}".lower()
    found = [t for t in TOOLS if t in haystack]
    return found[0] if len(found) == 1 else None


@dataclass
class _Captured:
    tool: str
    run: dict[str, Any]
    job: dict[str, Any]
    log: bytes | None


def _pick_job(gh: GitHub, repo: str, run: dict[str, Any]) -> dict[str, Any]:
    jobs = cast(
        list[dict[str, Any]],
        gh.get_json(f"repos/{repo}/actions/runs/{run['id']}/jobs?per_page=100")["jobs"],
    )
    if run["conclusion"] == "success":
        candidates = jobs
    else:
        candidates = [j for j in jobs if j["conclusion"] != "success"]
    if len(candidates) != 1:
        names = [f"{j['name']} ({j['conclusion']})" for j in jobs]
        what = "job" if run["conclusion"] == "success" else "failed job"
        raise CaptureError(f"run {run['id']}: expected exactly one {what}, found {names}")
    return candidates[0]


def _merge_base(gh: GitHub, repo: str, job_id: int) -> str | None:
    raw = gh.get_bytes(f"repos/{repo}/actions/jobs/{job_id}/logs")
    return extract_log_facts(raw.decode("utf-8", errors="replace")).merge_base


def build_meta(
    gh: GitHub, repo: str, specs: list[RunSpec]
) -> tuple[dict[str, Any], dict[str, bytes]]:
    """Return (meta dict, {log file name: raw bytes})."""
    captured: list[_Captured] = []
    for spec in specs:
        run = cast(dict[str, Any], gh.get_json(f"repos/{repo}/actions/runs/{spec.run_id}"))
        if run.get("status") != "completed":
            raise CaptureError(f"run {spec.run_id} is not completed (status {run.get('status')})")
        tool = spec.tool or infer_tool(run)
        if tool is None:
            raise CaptureError(
                f"run {spec.run_id}: cannot tell maven/gradle from workflow "
                f"{run.get('path')!r}; pass it as maven={spec.run_id} or gradle={spec.run_id}"
            )
        job = _pick_job(gh, repo, run)
        log = None
        if run["conclusion"] != "success":
            log = gh.get_bytes(f"repos/{repo}/actions/jobs/{job['id']}/logs")
        captured.append(_Captured(tool=tool, run=run, job=job, log=log))

    tools = [c.tool for c in captured]
    if len(set(tools)) != len(tools):
        raise CaptureError(f"one run per build tool, got {tools}")
    for key in ("head_sha", "event"):
        values = {c.run[key] for c in captured}
        if len(values) != 1:
            raise CaptureError(f"runs disagree on {key}: {sorted(values)}")
    if not any(c.log for c in captured):
        raise CaptureError("no failed run given; a case needs at least one failed log")

    facts = [extract_log_facts(c.log.decode("utf-8", errors="replace")) for c in captured if c.log]
    head_sha = captured[0].run["head_sha"]
    event = captured[0].run["event"]

    jdks = {f.java_version for f in facts if f.java_version}
    if len(jdks) != 1:
        raise CaptureError(f"expected one java-version across logs, found {sorted(jdks)}")
    labels = {(c.job.get("labels") or ["?"])[0] for c in captured}
    if len(labels) != 1:
        raise CaptureError(f"runs use different runners: {sorted(labels)}")

    base_sha = None
    if event == "pull_request":
        bases = {f.merge_base for f in facts}
        if len(bases) != 1 or None in bases:
            raise CaptureError(f"PR logs disagree on / lack the merge base: {bases}")
        base_sha = bases.pop()

    runs: dict[str, dict[str, Any]] = {}
    logs: dict[str, bytes] = {}
    for c in sorted(captured, key=lambda c: TOOLS.index(c.tool)):
        entry: dict[str, Any] = {
            "run_id": c.run["id"],
            "job_id": c.job["id"],
            "conclusion": c.run["conclusion"],
            "attempts": c.run["run_attempt"],
        }
        if c.log is not None:
            entry["log"] = LOG_NAMES[c.tool]
            logs[LOG_NAMES[c.tool]] = c.log
        runs[c.tool] = entry

    captured_ids = {c.run["id"] for c in captured}
    related: list[dict[str, Any]] = []
    others = gh.get_json(f"repos/{repo}/actions/runs?head_sha={head_sha}&per_page=100")
    for other in sorted(others["workflow_runs"], key=lambda r: r["id"]):
        tool = infer_tool(other)
        if other["id"] in captured_ids or tool is None or other.get("status") != "completed":
            continue
        rel: dict[str, Any] = {
            "tool": tool,
            "run_id": other["id"],
            "event": other["event"],
            "conclusion": other["conclusion"],
        }
        if other["event"] == "pull_request":
            job = _pick_job(gh, repo, other)
            if (base := _merge_base(gh, repo, job["id"])) is not None:
                rel["base_sha"] = base
        related.append(rel)

    meta: dict[str, Any] = {
        "repo": repo,
        "event": event,
        "head_sha": head_sha,
        **({"base_sha": base_sha} if base_sha else {}),
        "runner_os": labels.pop(),
        "jdk": jdks.pop(),
        "runs": runs,
        **({"related_runs": related} if related else {}),
    }
    return meta, logs


def capture(
    gh: GitHub,
    repo: str,
    case_id: str,
    specs: list[RunSpec],
    cases_dir: Path = CASES_DIR,
    force: bool = False,
) -> list[str]:
    """Write the case; return consistency problems (empty = all good)."""
    if "/" in case_id or case_id in {"", ".", ".."}:
        raise CaptureError(f"invalid case id {case_id!r}")
    case_dir = cases_dir / case_id
    existing = [p.name for p in case_dir.glob("*") if p.name == "meta.yaml" or p.suffix == ".log"]
    if existing and not force:
        raise CaptureError(f"{case_dir} already has {sorted(existing)}; pass --force to replace")

    meta, logs = build_meta(gh, repo, specs)
    leaks = find_forbidden_keys(meta)
    if leaks:
        raise CaptureError(f"refusing to write label-leaking keys: {leaks}")
    try:
        CaseMeta.model_validate(meta)
    except ValueError as e:
        raise CaptureError(f"generated meta is invalid: {e}") from e

    case_dir.mkdir(parents=True, exist_ok=True)
    for name in LOG_NAMES.values():
        if name not in logs:
            (case_dir / name).unlink(missing_ok=True)
    for name, data in logs.items():
        (case_dir / name).write_bytes(data)
    (case_dir / "meta.yaml").write_text(
        HEADER + yaml.safe_dump(meta, sort_keys=False, default_flow_style=None, width=100)
    )
    try:
        return check_case(case_id, cases_dir)
    except CaseError as e:
        return [str(e)]


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        prog="python -m evals.capture_case", description=__doc__.split("\n")[0]
    )
    p.add_argument("--repo", required=True, help="owner/name")
    p.add_argument("--case", required=True, help="case id, e.g. case-04")
    p.add_argument(
        "--run",
        required=True,
        action="append",
        type=parse_run_spec,
        help="run id, optionally tool=ID (maven=123); repeat per build tool",
    )
    p.add_argument("--cases-dir", type=Path, default=CASES_DIR)
    p.add_argument("--force", action="store_true", help="replace an existing case's meta and logs")
    args = p.parse_args(argv)

    try:
        problems = capture(GhCli(), args.repo, args.case, args.run, args.cases_dir, args.force)
    except CaptureError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    print(f"wrote {args.cases_dir / args.case}/meta.yaml")
    for prob in problems:
        print(f"inconsistent: {prob}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
