import argparse
from pathlib import Path
from typing import Any

import pytest
import yaml

from evals.capture_case import CaptureError, RunSpec, capture, parse_run_spec
from tests.test_consistency import BASE, HEAD, pr_log, push_log

REPO = "o/r"


class FakeGitHub:
    """Serves canned API responses; records every path requested."""

    def __init__(self) -> None:
        self.json: dict[str, Any] = {}
        self.bytes: dict[str, bytes] = {}
        self.requested: list[str] = []

    def get_json(self, path: str) -> Any:
        self.requested.append(path)
        return self.json[path]

    def get_bytes(self, path: str) -> bytes:
        self.requested.append(path)
        return self.bytes[path]

    def add_run(
        self,
        run_id: int,
        tool: str,
        conclusion: str,
        *,
        event: str = "push",
        log: str | None = None,
        job_conclusion: str | None = None,
    ) -> None:
        job_id = run_id * 10
        self.json[f"repos/{REPO}/actions/runs/{run_id}"] = {
            "id": run_id,
            "name": f"Java CI with {tool.title()}",
            "path": f".github/workflows/{tool}-build.yml",
            "event": event,
            "status": "completed",
            "conclusion": conclusion,
            "run_attempt": 1,
            "head_sha": HEAD,
            "head_branch": "case/99",  # must never reach meta.yaml
            "display_title": "Fix the thing",  # must never reach meta.yaml
        }
        self.json[f"repos/{REPO}/actions/runs/{run_id}/jobs?per_page=100"] = {
            "jobs": [
                {
                    "id": job_id,
                    "name": "build (17)",
                    "conclusion": job_conclusion or conclusion,
                    "labels": ["ubuntu-latest"],
                }
            ]
        }
        if log is not None:
            self.bytes[f"repos/{REPO}/actions/jobs/{job_id}/logs"] = log.encode()

    def set_head_runs(self, *run_ids: int) -> None:
        self.json[f"repos/{REPO}/actions/runs?head_sha={HEAD}&per_page=100"] = {
            "workflow_runs": [self.json[f"repos/{REPO}/actions/runs/{i}"] for i in run_ids]
        }


@pytest.fixture
def gh() -> FakeGitHub:
    return FakeGitHub()


def _meta(tmp_path: Path, case_id: str = "case-x") -> dict[str, Any]:
    text = (tmp_path / case_id / "meta.yaml").read_text()
    assert text.startswith("# Generated by evals/capture_case.py")
    data: dict[str, Any] = yaml.safe_load(text)
    return data


def test_push_case(gh: FakeGitHub, tmp_path: Path) -> None:
    gh.add_run(100, "maven", "success")
    gh.add_run(200, "gradle", "failure", log=push_log())
    gh.set_head_runs(100, 200)

    problems = capture(gh, REPO, "case-x", [RunSpec(100), RunSpec(200)], tmp_path)

    assert problems == []
    assert _meta(tmp_path) == {
        "repo": REPO,
        "event": "push",
        "head_sha": HEAD,
        "runner_os": "ubuntu-latest",
        "jdk": "17",
        "runs": {
            "maven": {"run_id": 100, "job_id": 1000, "conclusion": "success", "attempts": 1},
            "gradle": {
                "run_id": 200,
                "job_id": 2000,
                "conclusion": "failure",
                "attempts": 1,
                "log": "gradle.log",
            },
        },
    }
    assert (tmp_path / "case-x/gradle.log").read_bytes() == push_log().encode()  # BOM kept
    assert not (tmp_path / "case-x/maven.log").exists()


def test_never_writes_branch_or_title(gh: FakeGitHub, tmp_path: Path) -> None:
    gh.add_run(200, "gradle", "failure", log=push_log())
    gh.set_head_runs(200)
    capture(gh, REPO, "case-x", [RunSpec(200)], tmp_path)
    text = (tmp_path / "case-x/meta.yaml").read_text()
    assert (
        "case/99" not in text
        and "Fix the thing" not in text
        and "branch" not in text.split("\n", 2)[2]
    )


def test_pr_case_with_related_runs(gh: FakeGitHub, tmp_path: Path) -> None:
    old_base = "d" * 40
    gh.add_run(100, "maven", "failure", event="pull_request", log=pr_log())
    gh.add_run(50, "maven", "success", event="pull_request", log=pr_log(base=old_base))
    gh.add_run(40, "maven", "success", event="push")
    gh.set_head_runs(100, 50, 40)

    assert capture(gh, REPO, "case-x", [RunSpec(100)], tmp_path) == []
    meta = _meta(tmp_path)
    assert meta["base_sha"] == BASE
    assert meta["related_runs"] == [
        {"tool": "maven", "run_id": 40, "event": "push", "conclusion": "success"},
        {
            "tool": "maven",
            "run_id": 50,
            "event": "pull_request",
            "conclusion": "success",
            "base_sha": old_base,
        },
    ]


def test_refuses_to_overwrite_without_force(gh: FakeGitHub, tmp_path: Path) -> None:
    gh.add_run(200, "gradle", "failure", log=push_log())
    gh.set_head_runs(200)
    capture(gh, REPO, "case-x", [RunSpec(200)], tmp_path)
    with pytest.raises(CaptureError, match="--force"):
        capture(gh, REPO, "case-x", [RunSpec(200)], tmp_path)


def test_force_replaces_and_removes_stale_logs(gh: FakeGitHub, tmp_path: Path) -> None:
    (tmp_path / "case-x").mkdir()
    (tmp_path / "case-x/maven.log").write_text("stale")
    (tmp_path / "case-x/expected.yaml").write_text("answer key")
    gh.add_run(200, "gradle", "failure", log=push_log())
    gh.set_head_runs(200)

    assert capture(gh, REPO, "case-x", [RunSpec(200)], tmp_path, force=True) == []
    assert not (tmp_path / "case-x/maven.log").exists()
    assert (tmp_path / "case-x/expected.yaml").read_text() == "answer key"  # untouched


def test_only_get_requests_to_expected_endpoints(gh: FakeGitHub, tmp_path: Path) -> None:
    gh.add_run(200, "gradle", "failure", log=push_log())
    gh.set_head_runs(200)
    capture(gh, REPO, "case-x", [RunSpec(200)], tmp_path)
    assert all(p.startswith(f"repos/{REPO}/actions/") for p in gh.requested)


def test_runs_with_different_head_sha_rejected(gh: FakeGitHub, tmp_path: Path) -> None:
    gh.add_run(100, "maven", "failure", log=push_log())
    gh.add_run(200, "gradle", "failure", log=push_log())
    gh.json[f"repos/{REPO}/actions/runs/200"]["head_sha"] = "e" * 40
    with pytest.raises(CaptureError, match="disagree on head_sha"):
        capture(gh, REPO, "case-x", [RunSpec(100), RunSpec(200)], tmp_path)
    assert not (tmp_path / "case-x").exists()


def test_two_runs_for_one_tool_rejected(gh: FakeGitHub, tmp_path: Path) -> None:
    gh.add_run(100, "maven", "failure", log=push_log())
    gh.add_run(101, "maven", "failure", log=push_log())
    with pytest.raises(CaptureError, match="one run per build tool"):
        capture(gh, REPO, "case-x", [RunSpec(100), RunSpec(101)], tmp_path)


def test_needs_at_least_one_failed_run(gh: FakeGitHub, tmp_path: Path) -> None:
    gh.add_run(100, "maven", "success")
    with pytest.raises(CaptureError, match="at least one failed"):
        capture(gh, REPO, "case-x", [RunSpec(100)], tmp_path)


def test_multiple_failed_jobs_rejected(gh: FakeGitHub, tmp_path: Path) -> None:
    gh.add_run(100, "maven", "failure", log=push_log())
    jobs = gh.json[f"repos/{REPO}/actions/runs/100/jobs?per_page=100"]["jobs"]
    jobs.append({**jobs[0], "id": 1001, "name": "build (21)"})
    with pytest.raises(CaptureError, match="exactly one failed job"):
        capture(gh, REPO, "case-x", [RunSpec(100)], tmp_path)


def test_unknown_workflow_needs_explicit_tool(gh: FakeGitHub, tmp_path: Path) -> None:
    gh.add_run(100, "maven", "failure", log=push_log())
    run = gh.json[f"repos/{REPO}/actions/runs/100"]
    run["path"], run["name"] = ".github/workflows/ci.yml", "CI"
    gh.set_head_runs(100)
    with pytest.raises(CaptureError, match="maven=100"):
        capture(gh, REPO, "case-x", [RunSpec(100)], tmp_path)
    assert capture(gh, REPO, "case-x", [RunSpec(100, "maven")], tmp_path) == []


def test_reports_inconsistency(gh: FakeGitHub, tmp_path: Path) -> None:
    # The API says failure, but the job log ends in a cancellation.
    gh.add_run(200, "gradle", "failure", log=push_log(tail="##[error]The operation was canceled."))
    gh.set_head_runs(200)
    [problem] = capture(gh, REPO, "case-x", [RunSpec(200)], tmp_path)
    assert "cancelled, meta says failure" in problem


@pytest.mark.parametrize(
    ("text", "expected"),
    [("123", RunSpec(123)), ("maven=5", RunSpec(5, "maven")), ("gradle=7", RunSpec(7, "gradle"))],
)
def test_parse_run_spec(text: str, expected: RunSpec) -> None:
    assert parse_run_spec(text) == expected


@pytest.mark.parametrize("text", ["bazel=1", "maven=x", "abc"])
def test_parse_run_spec_rejects(text: str) -> None:
    with pytest.raises(argparse.ArgumentTypeError):
        parse_run_spec(text)
